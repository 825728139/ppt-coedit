import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1500,height:950}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto('http://127.0.0.1:5173');await page.waitForFunction(()=>window.pptAgent?.inspect().pages.length);
 await page.click('#add-text');
 const frame=()=>page.frameLocator('.gjs-frame');
 const text=()=>frame().getByText('双击编辑文字',{exact:true});
 await text().click();
 assert.equal(await page.locator('#layout-kind').innerText(),'自由定位');
 await page.locator('#quick-size').fill('48');await page.locator('#quick-size').press('Tab');
 assert.equal(await text().evaluate(el=>getComputedStyle(el).fontSize),'48px');
 await page.click('#quick-bold');assert.equal(await text().evaluate(el=>getComputedStyle(el).fontWeight),'700');
 await text().click();const left=await text().evaluate(el=>parseFloat(getComputedStyle(el).left));
 await page.keyboard.press('ArrowRight');
 assert.equal(await text().evaluate(el=>parseFloat(getComputedStyle(el).left)),left+1);
 await page.keyboard.press('Shift+ArrowRight');
 assert.equal(await text().evaluate(el=>parseFloat(getComputedStyle(el).left)),left+11);
 await page.click('#undo');assert.equal(await text().evaluate(el=>parseFloat(getComputedStyle(el).left)),left+1);
 await page.click('#add-card');
 await frame().getByText('一个值得分享的想法',{exact:true}).click({modifiers:['Alt']});
 assert.match(await page.locator('#layout-kind').innerText(),/FLEX/);
 const before=await frame().getByText('一个值得分享的想法',{exact:true}).evaluate(el=>el.style.cssText);
 await page.keyboard.press('ArrowRight');
 assert.equal(await frame().getByText('一个值得分享的想法',{exact:true}).evaluate(el=>el.style.cssText),before);
 await page.click('#object-parent');
 await page.locator('#quick-gap').fill('24');await page.locator('#quick-gap').press('Tab');
 assert.equal(await frame().locator('.card').evaluate(el=>getComputedStyle(el).gap),'24px');
 const chooserPromise=page.waitForEvent('filechooser');await page.click('#add-image');
 await (await chooserPromise).setFiles({name:'before.svg',mimeType:'image/svg+xml',buffer:Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100"><rect width="100" height="100" fill="red"/></svg>')});
 const image=()=>frame().locator('.slide-object[src^="data:image/"]');await image().waitFor();await image().click();
 const geometry=await image().evaluate(el=>{const s=getComputedStyle(el);return [s.left,s.top,s.width,s.height]});
 const src=await image().getAttribute('src');
 await page.setInputFiles('#replace-image-file',{name:'after.svg',mimeType:'image/svg+xml',buffer:Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="200" height="100"><rect width="200" height="100" fill="blue"/></svg>')});
 await page.waitForTimeout(150);assert.notEqual(await image().getAttribute('src'),src);
 assert.deepEqual(await image().evaluate(el=>{const s=getComputedStyle(el);return [s.left,s.top,s.width,s.height]}),geometry);
 await page.click('#undo');assert.equal(await image().getAttribute('src'),src);
 assert.deepEqual(errors,[]);
 console.log('PASS: typography, 1/10px nudge, undo, flow protection, parent selection, gap, image replacement preserves geometry and undo');
}finally{await browser.close()}
